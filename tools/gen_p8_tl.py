def parse_script():
    txt = io.open(SCRIPT, encoding='utf-8').read()
    items = []
    for line in txt.splitlines():
        m = re.match(r'^\s+(s|l|ha|k|si|t|th) "([^"]*)"$', line)
        if m:
            kind = 'thoughs' if m.group(1) == 'th' else 'dialogs'
            items.append((kind, m.group(2)))
            continue
        m = re.match(r'^\s+"([^"]*)":$', line)
        if m and not m.group(1).startswith('{"char"'):
            items.append(('choises', m.group(1)))
    return items


def fmt_pair(old, new):
    return '\n    old "%s"\n    new "%s"\n' % (old, new)


def main():
    apply = '--apply' in sys.argv
    items = parse_script()
    print('script items:', len(items), ' translations:', len(T))
    if len(items) != len(T):
        print('COUNT MISMATCH')
        return 1
    # выравнивание bucket'ов и пропуск переиспользуемых
    pairs, skipped = [], []
    for (kind, old), (tbucket, ja, ru) in zip(items, T):
        if kind != tbucket:
            print('KIND MISMATCH:', kind, tbucket, repr(old))
            return 1
        if old.startswith(SKIP_PREFIX):
            skipped.append(old)
            continue
        pairs.append((tbucket, old, ja, ru))
    print('to write:', len(pairs), ' skipped (reuse):', len(skipped))
    # уникальность olds внутри набора
    olds = [p[1] for p in pairs]
    dup = sorted({o for o in olds if olds.count(o) > 1})
    if dup:
        print('DUP IN SET:', dup)
        return 1
    # коллизии с уже существующими парами
    coll = []
    for lang in ('ja', 'ru'):
        content = {}
        for b in ('dialogs', 'thoughs', 'choises'):
            content[b] = io.open(TL[lang][b], encoding='utf-8').read()
        for b, old, _ja, _ru in pairs:
            if '    old "%s"\n' % old in content[b]:
                coll.append((lang, b, old))
    if coll:
        print('COLLISIONS WITH EXISTING:')
        for c in coll:
            print(' ', c[0], c[1], repr(c[2]))
        return 1
    # проверка пропущенных: пары уже есть
    for lang in ('ja', 'ru'):
        blob = io.open(TL[lang]['choises'], encoding='utf-8').read()
        for old in skipped:
            if '    old "%s"\n' % old not in blob:
                print('REUSE PAIR MISSING:', lang, repr(old))
                return 1
    print('reuse pairs present: OK')
    if not apply:
        print('dry-run OK (no write). Use --apply to write.')
        return 0
    counts = {}
    for lang in ('ja', 'ru'):
        for b, old, ja, ru in pairs:
            new = ja if lang == 'ja' else ru
            with io.open(TL[lang][b], 'a', encoding='utf-8', newline='\n') as f:
                f.write(fmt_pair(old, new))
            counts[(lang, b)] = counts.get((lang, b), 0) + 1
    print('written:', dict(counts))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
