# -*- coding: utf-8 -*-
"""Генератор tl (japanese/russian) + приложение манифеста голосов для ch7_1.

Едина свёрка данных с tools/gen_ch7_1_common.py (жёсткие проверки).
Пишет добавочные блоки в конец:
  game/tl/{japanese,russian}/dialogs.rpy     (140 пар)
  game/tl/{japanese,russian}/thoughs.rpy     (2 пары)
  game/tl/{japanese,russian}/choises.rpy     (9 пар)
  game/tl/{japanese,russian}/overlays.rpy    (титул, 1 пара)
  references/voice_id_map.csv                (140 строк)

Правки текстов — в tools/ch7_1_en.py / tools/ch7_1_ru.py, затем перегенерация.
"""
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_ch7_1_common as CC

TAG_JA = u"七个... "   # заменено ниже (литерал нарочно вынесен из строк с запятой)

def load_tl_tail(path):
    """Проверить отсутствие ранее вставленных ch7-блоков (нельзя дублировать)."""
    t = io.open(path, encoding="utf-8").read()
    if u"# ===== ch7_1" in t:
        raise CC.Fail("%s уже содержит блок ch7_1 — нельзя добавлять вторично" % path)
    return t

def ess(s):
    return s.replace("\\", u"\\\\").replace('"', u'\\"')

def append_pairs(path, lang, pairs, header_note):
    t = load_tl_tail(path)
    L = []
    L.append(u"")
    L.append(u"")
    L.append(u"# ===== ch7_1 (generated by tools/gen_ch7_1_tl.py) =====")
    L.append(u"# %s" % header_note)
    L.append(u"translate %s strings:" % lang)
    for i, (old, new) in enumerate(pairs):
        if i:
            L.append(u"")
        L.append(u'    old "%s"' % ess(old))
        L.append(u'    new "%s"' % new)
    with io.open(path, "a", encoding="utf-8", newline="\n") as f:
        f.write(u"\n".join(L) + u"\n")

def append_voice_manifest(rows):
    path = CC.rel("references", "voice_id_map.csv")
    t = io.open(path, encoding="utf-8").read()
    for name, vid, wav in rows:
        if re.search(r"^%s," % re.escape(name), t, re.M):
            raise CC.Fail("voice_id_map уже содержит строку %s" % name)
    with io.open(path, "a", encoding="utf-8", newline="\n") as f:
        f.write(u"\n".join(u"%s,%s,%s" % (name, vid, wav) for name, vid, wav in rows) + u"\n")

TITLE_JA = u"七章「失望のお姫さま」"
TITLE_RU = u"Глава седьмая: «Разочарованная принцесса»"

def build():
    data = CC.full_check()
    d = data["dialogs"]
    ths, chs = data["ths"], data["choices"]

    pairs_ja, pairs_ru = {}, {}

    # dialogs
    pairs_ja[CC.rel("game", "tl", "japanese", "dialogs.rpy")] = [
        (u"%s{#%s}" % (x["en"], x["name"]), x["ja"]) for x in d]
    pairs_ru[CC.rel("game", "tl", "russian", "dialogs.rpy")] = [
        (u"%s{#%s}" % (x["en"], x["name"]), x["ru"]) for x in d]

    # thoughs
    th_tags = [u"ch7_th_375%s" % x for x in "ab"]
    pairs_ja[CC.rel("game", "tl", "japanese", "thoughs.rpy")] = [
        (u"%s{#%s}" % (ths[i]["en"], th_tags[i]), ths[i]["ja"]) for i in (0, 1)]
    pairs_ru[CC.rel("game", "tl", "russian", "thoughs.rpy")] = [
        (u"%s{#%s}" % (ths[i]["en"], th_tags[i]), ths[i]["ru"]) for i in (0, 1)]

    # choises
    pairs_ja[CC.rel("game", "tl", "japanese", "choises.rpy")] = [
        (u"%s{#ch7_c%d}" % (c["en"], c["target"]), c["ja"]) for c in chs]
    pairs_ru[CC.rel("game", "tl", "russian", "choises.rpy")] = [
        (u"%s{#ch7_c%d}" % (c["en"], c["target"]), c["ru"]) for c in chs]

    # overlays (титул)
    pairs_ja[CC.rel("game", "tl", "japanese", "overlays.rpy")] = [
        (u"Chapter Seven: 'The Disappointed Princess'{#ch7_title}", TITLE_JA)]
    pairs_ru[CC.rel("game", "tl", "russian", "overlays.rpy")] = [
        (u"Chapter Seven: 'The Disappointed Princess'{#ch7_title}", TITLE_RU)]

    for path, plist in pairs_ja.items():
        append_pairs(path, "japanese", plist, u"часть 1 главы 7 (сцены 375-388)")
    for path, plist in pairs_ru.items():
        append_pairs(path, "russian", plist, u"часть 1 главы 7 (сцены 375-388)")

    append_voice_manifest(data["voice_rows"])
    print("OK: tl (%d jp, %d ru пар) + манифест голосов (%d)"
          % (len(d) + len(ths) + len(chs) + 1, len(d) + len(ths) + len(chs) + 1,
             len(data["voice_rows"])))

if __name__ == "__main__":
    build()
    print("OK tl")
