# ---------- Helper: write TL files ----------
def write_dialogs(lang, new_strings, header):
    p = f"game/tl/{lang}/ch10_1_dialogs.rpy"
    with open(p, "w", encoding="utf-8") as f:
        f.write(header + "\n")
        f.write(f"translate {lang} strings:\n\n")
        for (voiced, spk, en, tag), new in zip(dlg, new_strings):
            # Ensure old string matches script exactly
            old = f'{en}{{#' + tag + '}'
            f.write(f"    old \"{old}\"\n")
            f.write(f"    new \"{new}\"\n\n")
    print(f"wrote {p}")

# ---------- Read script, extract dialogue ----------
with open(SCRIPT, encoding="utf-8") as f:
    script_lines = f.read().split('\n')

dlg = []
pending = None
for ln in script_lines:
    vm = re.match(r'\s*voice\s+"(ch10_([a-z]+)_(\d+))"', ln)
    if vm:
        pending = True
        continue
    dm = re.match(r'\s*([a-z]+)\s+"(.+?)\{#(.+?)\}"', ln)
    if dm:
        dlg.append((pending, dm.group(1), dm.group(2), dm.group(3)))
        pending = None
assert len(dlg) == 174, f"dialog lines {len(dlg)}"

