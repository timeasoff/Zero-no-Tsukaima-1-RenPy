def apply(path, fixes):
    src = io.open(path, encoding="utf-8").read()
    out = src
    for key, (old, new) in sorted(fixes.items()):
        # в исходнике переносы строк записаны как escape-последовательность \n
        old = old.replace("\n", "\\n")
        new = new.replace("\n", "\\n")
        needle = '"%s": "%s"' % (key, old)
        if needle not in out:
            print("!! НЕ НАЙДЕНО: %s" % key)
            continue
        out = out.replace(needle, '"%s": "%s"' % (key, new), 1)
        print("ok: %s" % key)
    if out == src:
        print("изменений нет")
        return
    if "--apply" in sys.argv:
        io.open(path, "w", encoding="utf-8").write(out)
        print("записано: %s" % path)


if __name__ == "__main__":
    print("--- RU ---")
    apply(RU, RU_FIX)
    print("--- EN ---")
