def extract_voices_from_script(path):
    """Извлекает номера голосов из скрипта.
    Возвращает список (voice_name, speaker) в порядке появления.
    """
    results = []
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Ищем строки вида: voice "ch4.5_s_001"
    pattern = r'voice "(ch4\.5_([a-z]+)_(\d+))"'
    matches = re.findall(pattern, content)

    for full_name, spk, num in matches:
        results.append((full_name, spk, int(num)))

    return results


def main():
    apply = '--apply' in sys.argv

    script_voices = extract_voices_from_script(SCRIPT_PATH)
    canon_voices = CANON_VOICES

    print(f"Извлечено голосов из скрипта: {len(script_voices)}")
    print(f"Канонных голосов: {len(canon_voices)}")

    # Проверяем соответствие
    if len(script_voices) != len(canon_voices):
        print(f"\n!! MISMATCH: {len(script_voices)} vs {len(canon_voices)}")
        return

    # Проверяем коды говорящих
    for i, ((script_name, script_spk, script_num), (canon_id, canon_spk, canon_text)) in enumerate(zip(script_voices, canon_voices)):
        if script_spk != canon_spk:
            print(f"\n!! SPEAKER MISMATCH at {i}: script={script_spk} canon={canon_spk}")
            print(f"   Script: {script_name}")
            print(f"   Canon: {canon_id} ({canon_spk})")
            return

    # Генерируем строки манифеста
    manifest_lines = []
    for (script_name, script_spk, script_num), (canon_id, canon_spk, canon_text) in zip(script_voices, canon_voices):
        # Формат колонок манифеста: voice_name,voice_id (wav_file/notes не заполняются)
        manifest_lines.append(f"{script_name},{canon_id}")

    print(f"\nСгенерировано строк манифеста: {len(manifest_lines)}")

    if not apply:
        print("\n--- DRY RUN ---")
        print("Первые 5 строк манифеста:")
        for line in manifest_lines[:5]:
            print(f"  {line}")
        print("...")
        print("\nДля записи: python tools/gen_ch4_5_voices.py --apply")
        return

    # Записываем в манифест
    with open(MANIFEST_PATH, 'a', encoding='utf-8') as f:
        f.write("\n")
        for line in manifest_lines:
            f.write(line + "\n")

    print(f"\nМанифест обновлён: +{len(manifest_lines)} строк")


if __name__ == '__main__':
    main()
