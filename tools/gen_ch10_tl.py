# ------------------------------------------------------------------ write TL
def q(s):
    assert '"' not in s, f'quote in string: {s[:40]}'
    return '"' + s + '"'

def write_dialogs(lang, new_list, header):
    p = f"game/tl/{lang}/ch10_1_dialogs.rpy"
    body = [header, f"translate {lang} strings:", ""]
    for (voiced, spk, en, tag), new in zip(dlg, new_list):
        body.append(f"    old {q(en + '{#' + tag + '}')}")
        body.append(f"    new {q(new)}")
        body.append("")
    with open(p, "w", encoding="utf-8") as f:
        f.write("\n".join(body).rstrip() + "\n")
    print("wrote", p, len(new_list), "entries")

