# ------------------------------------------------------------------ read script
with open(SCRIPT, encoding="utf-8") as f:
    lines = f.read().split("\n")

spk_map_rev = None
counters = {}

# First pass: collect dialogue order (speaker sequence)
seq = []
pending_voice = None
for ln in lines:
    vm = re.match(r'\s*voice\s+"ch10_([a-z]+)_(\d+)"', ln)
    if vm:
        pending_voice = True
        continue
    dm = re.match(r'\s*([a-z]+)\s+"(.+?)\{#(.+?)\}"', ln)
    if dm:
        seq.append((pending_voice, dm.group(1)))
        pending_voice = None
assert len(seq) == 174, f"dialogue lines: {len(seq)}"

# new tags per speaker
new_tags = []
for voiced, spk in seq:
    counters[spk] = counters.get(spk, 0) + 1
    new_tags.append(f"ch10_{spk}_{counters[spk]:03d}")

# Second pass: rewrite script lines (tags + voice names)
out = []
di = 0
pending_voice_idx = None
for ln in lines:
    vm = re.match(r'\s*voice\s+"ch10_([a-z]+)_(\d+)"', ln)
    dm = re.match(r'(\s*[a-z]+\s+")(.+?)(\{#)(.+?)(\}")(.*)', ln)
    if vm:
        pending_voice_idx = len(out)
        out.append(ln)  # placeholder, patched when dialogue arrives
        continue
    if dm:
        voiced, spk = seq[di]
        tag = new_tags[di]
        out.append(dm.group(1) + dm.group(2) + "{#" + tag + "}" + dm.group(5) + dm.group(6))
        if voiced and pending_voice_idx is not None:
            indent = re.match(r'(\s*)', lines[pending_voice_idx]).group(1)
            out[pending_voice_idx] = f'{indent}voice "{tag}"'
        pending_voice_idx = None
        di += 1
        continue
    out.append(ln)

assert di == 174, f"rewrote {di} dialogue lines"
with open(SCRIPT, "w", encoding="utf-8") as f:
    f.write("\n".join(out))

