def parse_script():
    """Ordered rows: (bucket, old). Ja pairing happens in main()."""
    lines = io.open(SCRIPT, encoding='utf-8').read().split('\n')
    rows = []
    for i, ln in enumerate(lines):
        m = re.match(r'^    th "(.*)"\s*$', ln)
        if m:
            rows.append(('thoughs', m.group(1)))
            continue
        mv = re.match(r'^    voice "ch4\.4_\w+_\d+"\s*$', ln)
        if mv:
            ms = re.match(r'^    \w+ "(.*)"\s*$', lines[i + 1])
            rows.append(('dialogs', ms.group(1)))
            continue
        mch = re.match(r'^        "(.*)":\s*$', ln)
        if mch:
            rows.append(('choises', mch.group(1)))
            continue
        mmap = re.match(r'^\s+\$ choices\.append\(\{.*?"text": "(.*)".*\}\)$', ln)
        if mmap:
            rows.append(('choises', mmap.group(1)))
    return rows


def load_canon():
    scenes = {}
    cur = None
    for line in io.open(CANON, encoding='utf-8'):
        line = line.rstrip('\n')
        m = re.match(r'^SCENE (\d+) \(line (\d+)\)$', line)
        if m:
            cur = int(m.group(1))
            scenes.setdefault(cur, {'sp': [], 'th': [], 'kick': []})
            continue
        if cur is None:
            continue
        m = re.match(r'^  TALK \S+ \| v=(\S+) \| (.*)$', line)
        if m:
            if m.group(1) == 'NONE':
                scenes[cur]['th'].append(('th', m.group(2)))
            else:
                scenes[cur]['sp'].append(m.group(2))
            continue
        m = re.match(r'^  KICK 【選択肢】(.+?) → scene', line)
        if m:
            scenes[cur]['kick'].append(m.group(1))
    return scenes


